package com.harvana.app.web3;

/** The EIP-1193 provider injected at document start into the top-level page of the dApp browser. */
final class Provider {
    private Provider() {}

    static String script(String chainHex, String netVersion, String solChain) {
        return "(function(){\n"
            + "if (window.top !== window) return;\n"
            + "if (window.ethereum && window.ethereum.isHarvana) return;\n"
            + "var bridge = window.harvanaBridge; if (!bridge) return;\n"
            + "try { delete window.harvanaBridge; } catch(e) {}\n"
            + "var seq = 1, pending = {}, listeners = {}, hl = {}, solEvent = function(){};\n"
            + "function fire(ev, data){ (listeners[ev]||[]).slice().forEach(function(f){ try{ f(data); }catch(e){} }); }\n"
            + "bridge.onmessage = function(m){\n"
            + "  var o; try { o = JSON.parse(m.data); } catch(e) { return; }\n"
            + "  if (o.event && o.ns === 'solana') { solEvent(o.event, o.data); return; }\n"
            + "  if (o.event && o.ns === 'harvana') { (hl[o.event]||[]).slice().forEach(function(f){ try{ f(o.data); }catch(e){} }); return; }\n"
            + "  if (o.event) {\n"
            + "    if (o.event === 'chainChanged') { p.chainId = o.data; p.networkVersion = String(parseInt(o.data, 16)); }\n"
            + "    if (o.event === 'accountsChanged') { p.selectedAddress = o.data[0] || null; }\n"
            + "    fire(o.event, o.data); return;\n"
            + "  }\n"
            + "  var w = pending[o.id]; if (!w) return; delete pending[o.id];\n"
            + "  if (o.error) { var e = new Error(o.error.message); e.code = o.error.code; w.reject(e); }\n"
            + "  else {\n"
            + "    if (w.method === 'eth_requestAccounts' || w.method === 'eth_accounts') p.selectedAddress = (o.result && o.result[0]) || null;\n"
            + "    w.resolve(o.result);\n"
            + "  }\n"
            + "};\n"
            + "function request(args){\n"
            + "  return new Promise(function(resolve, reject){\n"
            + "    if (!args || typeof args.method !== 'string') { var e = new Error('Invalid request'); e.code = -32600; reject(e); return; }\n"
            + "    if (args.method === 'metamask_getProviderState') { request({method: 'eth_accounts'}).then(function(acc){\n"
            + "      resolve({isUnlocked: true, chainId: p.chainId, networkVersion: p.networkVersion, accounts: acc || []}); }, reject); return; }\n"
            + "    var id = seq++;\n"
            + "    pending[id] = {resolve: resolve, reject: reject, method: args.method};\n"
            + "    bridge.postMessage(JSON.stringify({id: id, method: args.method, params: args.params || []}));\n"
            + "  });\n"
            + "}\n"
            + "var p = {\n"
            + "  isHarvana: true, isMetaMask: true, chainId: '" + chainHex + "', networkVersion: '" + netVersion + "', selectedAddress: null,\n"
            + "  isConnected: function(){ return true; },\n"
            + "  _metamask: Object.freeze({ isUnlocked: function(){ return Promise.resolve(true); },\n"
            + "    requestBatch: function(reqs){ return Promise.all((reqs||[]).map(function(r){ return request(r); })); } }),\n"
            + "  request: request,\n"
            + "  enable: function(){ return request({method: 'eth_requestAccounts'}); },\n"
            + "  on: function(ev, f){ (listeners[ev] = listeners[ev] || []).push(f); return p; },\n"
            + "  once: function(ev, f){ var g = function(d){ p.removeListener(ev, g); f(d); }; return p.on(ev, g); },\n"
            + "  removeListener: function(ev, f){ listeners[ev] = (listeners[ev]||[]).filter(function(x){ return x !== f; }); return p; },\n"
            + "  off: function(ev, f){ return p.removeListener(ev, f); },\n"
            + "  removeAllListeners: function(ev){ if (ev) delete listeners[ev]; else listeners = {}; return p; },\n"
            + "  send: function(a, b){\n"
            + "    if (typeof a === 'string') return request({method: a, params: b});\n"
            + "    if (typeof b === 'function') return p.sendAsync(a, b);\n"
            + "    throw new Error('Synchronous calls are not supported');\n"
            + "  },\n"
            + "  sendAsync: function(payload, cb){\n"
            + "    request(payload).then(function(r){ cb(null, {id: payload.id, jsonrpc: '2.0', result: r}); },\n"
            + "                          function(e){ cb(e, {id: payload.id, jsonrpc: '2.0', error: {code: e.code, message: e.message}}); });\n"
            + "  }\n"
            + "};\n"
            + "var hv = Object.freeze({\n"
            + "  isHarvana: true, network: 'harvana',\n"
            + "  request: function(args){\n"
            + "    if (!args || typeof args.method !== 'string' || args.method.indexOf('harvana_') !== 0) { var e = new Error('Method not supported'); e.code = 4200; return Promise.reject(e); }\n"
            + "    return request(args);\n"
            + "  },\n"
            + "  on: function(ev, f){ (hl[ev] = hl[ev] || []).push(f); return hv; },\n"
            + "  removeListener: function(ev, f){ hl[ev] = (hl[ev]||[]).filter(function(x){ return x !== f; }); return hv; }\n"
            + "});\n"
            + "Object.defineProperty(window, 'harvana', {value: hv, writable: false, configurable: false});\n"
            + "Object.defineProperty(window, 'ethereum', {value: p, writable: false, configurable: false});\n"
            + "var ICON = 'data:image/svg+xml;base64,PHN2ZyB4bWxucz0iaHR0cDovL3d3dy53My5vcmcvMjAwMC9zdmciIHZpZXdCb3g9IjAgMCAzMiAzMiI+PGNpcmNsZSBjeD0iMTYiIGN5PSIxNiIgcj0iMTYiIGZpbGw9IiMxNkEzNEEiLz48dGV4dCB4PSIxNiIgeT0iMjIiIGZvbnQtc2l6ZT0iMTYiIGZvbnQtZmFtaWx5PSJzYW5zLXNlcmlmIiBmb250LXdlaWdodD0iYm9sZCIgZmlsbD0iI2ZmZiIgdGV4dC1hbmNob3I9Im1pZGRsZSI+SDwvdGV4dD48L3N2Zz4=';\n"
            + "var info = Object.freeze({uuid: '6f1d3c0e-8a2b-4c5d-9e7f-1a2b3c4d5e6f', name: 'Harvana', rdns: 'com.harvana.app', icon: ICON});\n"
            + "// Solana: window.solana / window.phantom.solana and a Wallet Standard wallet, over the same bridge.\n"
            + "var SOL_CHAIN = '" + solChain + "';\n"
            + "var sl = {}, solAcc = null;\n"
            + "function sfire(ev, d){ (sl[ev]||[]).slice().forEach(function(f){ try{ f(d); }catch(e){} }); }\n"
            + "function b64d(s){ var b = atob(s), u = new Uint8Array(b.length); for (var i = 0; i < b.length; i++) u[i] = b.charCodeAt(i); return u; }\n"
            + "function b64e(u){ var s = ''; for (var i = 0; i < u.length; i += 0x8000) s += String.fromCharCode.apply(null, u.subarray(i, i + 0x8000)); return btoa(s); }\n"
            + "function bytesOf(x){ if (x instanceof Uint8Array) return x; if (Array.isArray(x) || x instanceof ArrayBuffer) return new Uint8Array(x); throw new Error('Expected bytes'); }\n"
            + "function pk(addr, bytes){\n"
            + "  return Object.freeze({ toBase58: function(){ return addr; }, toString: function(){ return addr; }, toJSON: function(){ return addr; },\n"
            + "    toBytes: function(){ return bytes.slice(); }, toBuffer: function(){ return bytes.slice(); },\n"
            + "    equals: function(o){ return !!o && typeof o.toBase58 === 'function' && o.toBase58() === addr; } });\n"
            + "}\n"
            + "function txBytes(tx){\n"
            + "  if (tx instanceof Uint8Array) return tx;\n"
            + "  if (tx && 'version' in tx) return tx.serialize();\n"
            + "  if (tx && typeof tx.serialize === 'function') return tx.serialize({requireAllSignatures: false, verifySignatures: false});\n"
            + "  throw new Error('Expected a transaction');\n"
            + "}\n"
            + "function txFrom(orig, bytes){\n"
            + "  if (orig instanceof Uint8Array) return bytes;\n"
            + "  var C = orig.constructor;\n"
            + "  if ('version' in orig && typeof C.deserialize === 'function') return C.deserialize(bytes);\n"
            + "  if (typeof C.from === 'function') return C.from(bytes);\n"
            + "  return bytes;\n"
            + "}\n"
            + "function setAcc(r){\n"
            + "  var was = solAcc;\n"
            + "  solAcc = r ? {address: r.address, bytes: b64d(r.publicKey)} : null;\n"
            + "  sol.publicKey = solAcc ? pk(solAcc.address, solAcc.bytes) : null;\n"
            + "  sol.isConnected = !!solAcc;\n"
            + "  return was;\n"
            + "}\n"
            + "function stdAccount(){\n"
            + "  if (!solAcc) return null;\n"
            + "  return Object.freeze({address: solAcc.address, publicKey: solAcc.bytes.slice(), chains: [SOL_CHAIN],\n"
            + "    features: ['solana:signAndSendTransaction', 'solana:signTransaction', 'solana:signMessage']});\n"
            + "}\n"
            + "var stdl = [];\n"
            + "function stdChange(){ var a = stdAccount(); stdl.slice().forEach(function(f){ try{ f({accounts: a ? [a] : []}); }catch(e){} }); }\n"
            + "function solConnect(opts){\n"
            + "  return request({method: 'sol_connect', params: [{onlyIfTrusted: !!(opts && opts.onlyIfTrusted)}]}).then(function(r){\n"
            + "    setAcc(r); sfire('connect', sol.publicKey); stdChange(); return {publicKey: sol.publicKey};\n"
            + "  });\n"
            + "}\n"
            + "function solDisconnect(){\n"
            + "  return request({method: 'sol_disconnect', params: []}).then(function(){ setAcc(null); sfire('disconnect'); stdChange(); });\n"
            + "}\n"
            + "function notConnected(){ var e = new Error('Wallet not connected'); e.code = 4100; return Promise.reject(e); }\n"
            + "function solSignMessage(msg){\n"
            + "  if (!solAcc) return notConnected();\n"
            + "  var m = bytesOf(msg);\n"
            + "  return request({method: 'sol_signMessage', params: [b64e(m)]}).then(function(r){ return {signature: b64d(r.signature), publicKey: sol.publicKey}; });\n"
            + "}\n"
            + "function solSignTx(tx){\n"
            + "  if (!solAcc) return notConnected();\n"
            + "  return request({method: 'sol_signTransaction', params: [b64e(txBytes(tx))]}).then(function(r){ return txFrom(tx, b64d(r.transaction)); });\n"
            + "}\n"
            + "function solSignAll(txs){\n"
            + "  if (!solAcc) return notConnected();\n"
            + "  return request({method: 'sol_signAllTransactions', params: [txs.map(function(t){ return b64e(txBytes(t)); })]}).then(function(r){\n"
            + "    return r.transactions.map(function(b, i){ return txFrom(txs[i], b64d(b)); });\n"
            + "  });\n"
            + "}\n"
            + "function solSend(tx, opts){\n"
            + "  if (!solAcc) return notConnected();\n"
            + "  return request({method: 'sol_signAndSendTransaction', params: [b64e(txBytes(tx)), opts || {}]}).then(function(r){\n"
            + "    return {signature: r.signature, raw: b64d(r.raw), publicKey: sol.publicKey};\n"
            + "  });\n"
            + "}\n"
            + "var sol = {\n"
            + "  isPhantom: true, isHarvana: true, publicKey: null, isConnected: false,\n"
            + "  connect: solConnect, disconnect: solDisconnect,\n"
            + "  signMessage: solSignMessage,\n"
            + "  signTransaction: solSignTx,\n"
            + "  signAllTransactions: solSignAll,\n"
            + "  signAndSendTransaction: function(tx, opts){ return solSend(tx, opts).then(function(r){ return {signature: r.signature, publicKey: r.publicKey}; }); },\n"
            + "  request: function(a){\n"
            + "    var m = a && a.method, p = (a && a.params) || {};\n"
            + "    if (m === 'connect') return solConnect(p);\n"
            + "    if (m === 'disconnect') return solDisconnect();\n"
            + "    if (m === 'signMessage') return solSignMessage(p.message);\n"
            + "    if (m === 'signTransaction') return solSignTx(p.transaction);\n"
            + "    if (m === 'signAllTransactions') return solSignAll(p.transactions);\n"
            + "    if (m === 'signAndSendTransaction') return sol.signAndSendTransaction(p.transaction, p.options);\n"
            + "    var e = new Error('Method not supported'); e.code = 4200; return Promise.reject(e);\n"
            + "  },\n"
            + "  on: function(ev, f){ (sl[ev] = sl[ev] || []).push(f); return sol; },\n"
            + "  off: function(ev, f){ sl[ev] = (sl[ev]||[]).filter(function(x){ return x !== f; }); return sol; },\n"
            + "  removeListener: function(ev, f){ return sol.off(ev, f); },\n"
            + "  removeAllListeners: function(ev){ if (ev) delete sl[ev]; else sl = {}; return sol; }\n"
            + "};\n"
            + "solEvent = function(ev, d){\n"
            + "  if (ev === 'accountChanged') { setAcc(d); sfire('accountChanged', sol.publicKey); stdChange(); }\n"
            + "  else if (ev === 'disconnect') { setAcc(null); sfire('disconnect'); stdChange(); }\n"
            + "};\n"
            + "Object.defineProperty(window, 'solana', {value: sol, writable: false, configurable: false});\n"
            + "Object.defineProperty(window, 'phantom', {value: Object.freeze({solana: sol}), writable: false, configurable: false});\n"
            + "var stdWallet = {\n"
            + "  version: '1.0.0', name: 'Harvana', icon: ICON, chains: [SOL_CHAIN],\n"
            + "  get accounts(){ var a = stdAccount(); return a ? [a] : []; },\n"
            + "  features: {\n"
            + "    'standard:connect': {version: '1.0.0', connect: function(input){\n"
            + "      return solConnect({onlyIfTrusted: !!(input && input.silent)}).then(function(){ return {accounts: stdWallet.accounts}; },\n"
            + "        function(e){ if (input && input.silent) return {accounts: []}; throw e; });\n"
            + "    }},\n"
            + "    'standard:disconnect': {version: '1.0.0', disconnect: function(){ return solDisconnect(); }},\n"
            + "    'standard:events': {version: '1.0.0', on: function(ev, f){\n"
            + "      if (ev !== 'change') return function(){};\n"
            + "      stdl.push(f); return function(){ stdl = stdl.filter(function(x){ return x !== f; }); };\n"
            + "    }},\n"
            + "    'solana:signMessage': {version: '1.0.0', signMessage: function(){\n"
            + "      var ins = Array.prototype.slice.call(arguments), out = [];\n"
            + "      return ins.reduce(function(p, i){ return p.then(function(){ return solSignMessage(i.message).then(function(r){\n"
            + "        out.push({signedMessage: bytesOf(i.message), signature: r.signature}); }); }); }, Promise.resolve()).then(function(){ return out; });\n"
            + "    }},\n"
            + "    'solana:signTransaction': {version: '1.0.0', supportedTransactionVersions: ['legacy', 0], signTransaction: function(){\n"
            + "      var ins = Array.prototype.slice.call(arguments);\n"
            + "      if (ins.length === 1) return solSignTx(bytesOf(ins[0].transaction)).then(function(b){ return [{signedTransaction: b}]; });\n"
            + "      return solSignAll(ins.map(function(i){ return bytesOf(i.transaction); })).then(function(bs){ return bs.map(function(b){ return {signedTransaction: b}; }); });\n"
            + "    }},\n"
            + "    'solana:signAndSendTransaction': {version: '1.0.0', supportedTransactionVersions: ['legacy', 0], signAndSendTransaction: function(){\n"
            + "      var ins = Array.prototype.slice.call(arguments), out = [];\n"
            + "      return ins.reduce(function(p, i){ return p.then(function(){ return solSend(bytesOf(i.transaction), i.options).then(function(r){\n"
            + "        out.push({signature: r.raw}); }); }); }, Promise.resolve()).then(function(){ return out; });\n"
            + "    }}\n"
            + "  }\n"
            + "};\n"
            + "function stdRegister(api){ try { api.register(stdWallet); } catch(e) {} }\n"
            + "try { window.dispatchEvent(new CustomEvent('wallet-standard:register-wallet', {detail: stdRegister})); } catch(e) {}\n"
            + "try { window.addEventListener('wallet-standard:app-ready', function(e){ stdRegister(e.detail); }); } catch(e) {}\n"
            + "function announce(){ window.dispatchEvent(new CustomEvent('eip6963:announceProvider', {detail: Object.freeze({info: info, provider: p})})); }\n"
            + "window.addEventListener('eip6963:requestProvider', announce);\n"
            + "announce();\n"
            + "window.dispatchEvent(new Event('ethereum#initialized'));\n"
            + "window.dispatchEvent(new Event('harvana#initialized'));\n"
            + "})();";
    }
}
