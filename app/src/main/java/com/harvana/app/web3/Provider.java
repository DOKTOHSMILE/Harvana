package com.harvana.app.web3;

/** The EIP-1193 provider injected at document start into the top-level page of the dApp browser. */
final class Provider {
    private Provider() {}

    static String script(String chainHex, String netVersion) {
        return "(function(){\n"
            + "if (window.top !== window) return;\n"
            + "if (window.ethereum && window.ethereum.isHarvana) return;\n"
            + "var bridge = window.harvanaBridge; if (!bridge) return;\n"
            + "try { delete window.harvanaBridge; } catch(e) {}\n"
            + "var seq = 1, pending = {}, listeners = {};\n"
            + "function fire(ev, data){ (listeners[ev]||[]).slice().forEach(function(f){ try{ f(data); }catch(e){} }); }\n"
            + "bridge.onmessage = function(m){\n"
            + "  var o; try { o = JSON.parse(m.data); } catch(e) { return; }\n"
            + "  if (o.event) {\n"
            + "    if (o.event === 'chainChanged') { p.chainId = o.data; p.networkVersion = String(parseInt(o.data, 16)); }\n"
            + "    if (o.event === 'accountsChanged') { p.selectedAddress = o.data[0] || null; }\n"
            + "    fire(o.event, o.data); return;\n"
            + "  }\n"
            + "  var w = pending[o.id]; if (!w) return; delete pending[o.id];\n"
            + "  if (o.error) { var e = new Error(o.error.message); e.code = o.error.code; w.reject(e); }\n"
            + "  else {\n"
            + "    if (w.method === 'eth_requestAccounts' || w.method === 'eth_accounts') p.selectedAddress = (o.result && o.result[0]) || null;\n"
            + "    w.resolve(o.result);\n"
            + "  }\n"
            + "};\n"
            + "function request(args){\n"
            + "  return new Promise(function(resolve, reject){\n"
            + "    if (!args || typeof args.method !== 'string') { var e = new Error('Invalid request'); e.code = -32600; reject(e); return; }\n"
            + "    var id = seq++;\n"
            + "    pending[id] = {resolve: resolve, reject: reject, method: args.method};\n"
            + "    bridge.postMessage(JSON.stringify({id: id, method: args.method, params: args.params || []}));\n"
            + "  });\n"
            + "}\n"
            + "var p = {\n"
            + "  isHarvana: true, isMetaMask: true, chainId: '" + chainHex + "', networkVersion: '" + netVersion + "', selectedAddress: null,\n"
            + "  isConnected: function(){ return true; },\n"
            + "  request: request,\n"
            + "  enable: function(){ return request({method: 'eth_requestAccounts'}); },\n"
            + "  on: function(ev, f){ (listeners[ev] = listeners[ev] || []).push(f); return p; },\n"
            + "  once: function(ev, f){ var g = function(d){ p.removeListener(ev, g); f(d); }; return p.on(ev, g); },\n"
            + "  removeListener: function(ev, f){ listeners[ev] = (listeners[ev]||[]).filter(function(x){ return x !== f; }); return p; },\n"
            + "  off: function(ev, f){ return p.removeListener(ev, f); },\n"
            + "  removeAllListeners: function(ev){ if (ev) delete listeners[ev]; else listeners = {}; return p; },\n"
            + "  send: function(a, b){\n"
            + "    if (typeof a === 'string') return request({method: a, params: b});\n"
            + "    if (typeof b === 'function') return p.sendAsync(a, b);\n"
            + "    throw new Error('Synchronous calls are not supported');\n"
            + "  },\n"
            + "  sendAsync: function(payload, cb){\n"
            + "    request(payload).then(function(r){ cb(null, {id: payload.id, jsonrpc: '2.0', result: r}); },\n"
            + "                          function(e){ cb(e, {id: payload.id, jsonrpc: '2.0', error: {code: e.code, message: e.message}}); });\n"
            + "  }\n"
            + "};\n"
            + "Object.defineProperty(window, 'ethereum', {value: p, writable: false, configurable: false});\n"
            + "var info = Object.freeze({uuid: '6f1d3c0e-8a2b-4c5d-9e7f-1a2b3c4d5e6f', name: 'Harvana', rdns: 'com.harvana.app',\n"
            + "  icon: 'data:image/svg+xml;base64,PHN2ZyB4bWxucz0iaHR0cDovL3d3dy53My5vcmcvMjAwMC9zdmciIHZpZXdCb3g9IjAgMCAzMiAzMiI+PGNpcmNsZSBjeD0iMTYiIGN5PSIxNiIgcj0iMTYiIGZpbGw9IiMxNkEzNEEiLz48dGV4dCB4PSIxNiIgeT0iMjIiIGZvbnQtc2l6ZT0iMTYiIGZvbnQtZmFtaWx5PSJzYW5zLXNlcmlmIiBmb250LXdlaWdodD0iYm9sZCIgZmlsbD0iI2ZmZiIgdGV4dC1hbmNob3I9Im1pZGRsZSI+SDwvdGV4dD48L3N2Zz4='});\n"
            + "function announce(){ window.dispatchEvent(new CustomEvent('eip6963:announceProvider', {detail: Object.freeze({info: info, provider: p})})); }\n"
            + "window.addEventListener('eip6963:requestProvider', announce);\n"
            + "announce();\n"
            + "window.dispatchEvent(new Event('ethereum#initialized'));\n"
            + "})();";
    }
}
