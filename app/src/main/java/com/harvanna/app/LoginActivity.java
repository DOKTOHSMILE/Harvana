	private void initializeLogic() {
		androidx.appcompat.app.ActionBar ab = getSupportActionBar();
		int backgroundColor = androidx.core.content.ContextCompat.getColor(this, R.color.colorBackground);
		
		if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.LOLLIPOP) {
			final Window window = this.getWindow();
			window.clearFlags(WindowManager.LayoutParams.FLAG_TRANSLUCENT_STATUS);
			window.addFlags(WindowManager.LayoutParams.FLAG_DRAWS_SYSTEM_BAR_BACKGROUNDS);
			com.harvanna.app.utils.StatusBarUtil.matchToolbar(this);
		}
		
		directory = getIntent().getStringExtra("page"); 
		// THE FIX: getStringExtra() can return null if a future caller ever 
		// launches this screen without setting "page" (a deep link, a 	
		// notification tap-through, etc.) — the equals() call right after 
		// used to NPE unconditionally in that case. Every current caller 
		// does set it correctly, but this shouldn't depend on that holding 
		// forever. 
		if (directory != null && directory.equals("complete")) { 
			if (FirebaseAuth.getInstance().getCurrentUser() == null) {
				// Profile form requires a signed-in Firebase user; send back to the router.
				startActivity(new Intent(this, SplashScreenActivity.class));
				finish();
				return;
			}
			setTitle("Create account"); 		
			showFragment(complete); 
		} else if (directory != null && directory.equals("eLogin")) {
			setTitle("Sign in");
			showFragment(EmailAuthFragment.newInstance(false));
		} else if (directory != null && directory.equals("eCreate")) {
			setTitle("Create account");
			showFragment(EmailAuthFragment.newInstance(true));
		}
		
	}
	
